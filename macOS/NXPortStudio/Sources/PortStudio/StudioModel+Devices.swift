import AppKit
import PortCore
import UniformTypeIdentifiers

extension StudioModel {
    func refreshDevices() async {
        guard !isDiscoveringDevices else { return }
        isDiscoveringDevices = true
        defer { isDiscoveringDevices = false }
        do {
            let found = try await DeviceService.discover()
            devices = found
            if !found.contains(where: { $0.id == selectedDeviceID }) {
                selectedDeviceID = found.first(where: \.canInstall)?.id ?? found.first?.id ?? ""
            }
        } catch {
            failure = error.localizedDescription
            appendLog("Device discovery failed: \(error.localizedDescription)")
        }
    }

    func choosePreparedProject() {
        guard !isBusy else { return }
        let panel = NSOpenPanel()
        panel.title = t("Choose the game's prepared Xcode project")
        panel.canChooseFiles = true
        panel.canChooseDirectories = false
        panel.treatsFilePackagesAsDirectories = false
        if let type = UTType(filenameExtension: "xcodeproj") { panel.allowedContentTypes = [type] }
        if !gamePath.isEmpty { panel.directoryURL = URL(fileURLWithPath: gamePath) }
        guard panel.runModal() == .OK, let url = panel.url else { return }
        guard url.pathExtension == "xcodeproj",
              FileManager.default.fileExists(atPath: url.appendingPathComponent("project.pbxproj").path) else {
            failure = t("Choose the DmIOS.xcodeproj generated by nxnative.")
            return
        }
        projectURL = url
        failure = nil
    }

    func installPreparedProject() {
        guard !isBusy else { return }
        guard let projectURL else {
            failure = t("Prepare or select the game's Xcode project first.")
            return
        }
        guard let device = selectedDevice, device.canInstall else {
            failure = t("Connect and pair an iPhone or iPad with iOS 26 or later, and enable Developer Mode.")
            return
        }
        // Keep game-sized copies beside the extracted game on its original volume.
        let buildFolder = projectURL.deletingLastPathComponent().deletingLastPathComponent()
        let derivedData = buildFolder.appendingPathComponent("StudioDeployment", isDirectory: true)
        let plan: DeploymentPlan
        do {
            plan = try DeviceService.deploymentPlan(projectURL: projectURL, teamID: teamID,
                                                     device: device, derivedDataURL: derivedData)
        } catch {
            failure = error.localizedDescription
            return
        }
        UserDefaults.standard.set(teamID.trimmingCharacters(in: .whitespacesAndNewlines).uppercased(), forKey: "teamID")
        failure = nil
        isBusy = true
        status = "Signing and installing"
        stageName = "Xcode signing and device installation"
        stepName = ""
        stageIndex = 0
        stageTotal = 0
        progress = nil
        appendLog(plan.buildCommand.redactedDescription)
        let runID = UUID(); operationID = runID
        currentTask = Task { [self] in
            do {
                let app = try await DeviceService.buildAndInstall(plan, using: runner) { [weak self] line in
                    Task { @MainActor in
                        guard let self, self.operationID == runID else { return }
                        self.appendLog(line)
                    }
                }
                try Task.checkCancellation()
                completedURL = app
                status = "Installed on device"
                progress = 1
                appendLog("Installed on \(device.name).")
            } catch is CancellationError {
                status = "Cancelled"
                appendLog("Installation cancelled.")
            } catch {
                failure = error.localizedDescription
                status = "Installation failed"
                appendLog(error.localizedDescription)
            }
            operationID = UUID()
            isBusy = false
            currentTask = nil
        }
    }

    func openDevicesWindow() {
        guard let xcode = NSWorkspace.shared.urlForApplication(withBundleIdentifier: "com.apple.dt.Xcode"),
              NSWorkspace.shared.open(xcode) else {
            failure = t("Install and open Xcode to pair your device and add your Apple developer account.")
            return
        }
    }
}
