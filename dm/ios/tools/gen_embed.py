# Generate the embedded assembly: compile the rewritten module image into the executable, with code going into the single executable segment __TEXT only (Apple ITMS-90999: only one segment with execute permission is allowed).
#   __TEXT,__dm<name>x0   original text: [0, round16K(TEXT_END)) (includes part of the first ro page, read-only)
#   __DM<name>W,__img     RW segment: [round16K(TEXT_END), PATCH_OFF), rest of ro + data + bss (relocations land only here)
#   __TEXT,__dm<name>x1   patch area: [PATCH_OFF, round16K(end of file))
#   Modules with the patch area before the base (negative PATCH_OFF, see patch_nso.py FAR): W is [round16K(TEXT_END), FILE_IMAGE_LEN), x1 is the patch area after FILE_IMAGE_LEN in the file; bss and the key page are not in the executable
# The three pieces are not adjacent in the executable; at run time the loader (loader.c iOS branch) reserves one contiguous address range and vm_remaps them back at their original relative positions (code pages share the signed pages, W is copy-on-write),
# so the run-time layout is byte-identical to the original image: PC-relative addressing between original code and data, relative jumps in the patch area, and the host's "base + original offset" references all need no change.
# NROs (the modules a game loads at run time, after "--"; loader.c "NRO modules") share two sections instead: their code pieces in __TEXT,__dmnrox and their W parts in __DMNRO,__img,
# each piece 16K-aligned, with an index at the start of __dmnrox (NRO_INDEX below) that the loader finds them by. An executable can number at most 255 sections (a symbol's section number
# is 8 bits), so three per module did not link for Super Smash Bros. Ultimate's 98 NROs (ld trapped)
# Usage: gen_embed.py <build output dir> <output .S> <module name...> [-- <NRO module name...>]; link flags are printed to stdout (-segprot for the W segments)
import os, struct, sys
out, dst, args = sys.argv[1], sys.argv[2], sys.argv[3:]
names, nros = (args[:args.index('--')], args[args.index('--') + 1:]) if '--' in args else (args, [])
PG = 0x4000
def r16(x): return (x + PG - 1) & ~(PG - 1)
asm = ['// Generated by dm/ios/tools/gen_embed.py; do not edit']
flags = []
def pieces(n):   # (bin path, file size, [(kind, lo, hi)] for x0, W, x1) of a module
    hdr = dict(l[2:].split() for l in open(f'{out}/{n}.fixups.tsv'))
    te, po = int(hdr['TEXT_END'], 16), int(hdr['PATCH_OFF'], 16)
    ko, ks = int(hdr['KEY_PAGE_OFF'], 16), int(hdr['KEY_PAGE_SIZE'], 16)
    bin_ = os.path.abspath(f'{out}/{n}.patched.bin'); sz = os.path.getsize(bin_)
    a, end = r16(te), r16(sz)
    assert po > 0 and po % PG == 0 and a <= ko and ko + ks <= po and ko % PG == 0 and ks == PG, f'{n}: an NRO with the patch area before the base is not embedded'
    return bin_, sz, (('x0', 0, a), ('w', a, po), ('x1', po, end))
def incbin(bin_, sz, lo, hi):   # one 16K-aligned piece of a module image (zero-filled past the file's end)
    fill = min(hi, sz) - lo; r = ['    .p2align 14', f'    .incbin "{bin_}", {lo:#x}, {fill:#x}']
    if hi - lo > fill: r.append(f'    .space {hi - lo - fill:#x}')
    return r + ['    .p2align 14']
if nros:
    # NRO_INDEX at the start of __TEXT,__dmnrox: u32 magic 'DMNR', u32 count, then per NRO {char name[16], u64 x0 offset, u64 x0 length, u64 W offset, u64 W length, u64 x1 offset,
    # u64 x1 length}, x0 / x1 offsets from the start of __dmnrox, W offsets from the start of __DMNRO,__img; the index is padded to 16K
    ent = 16 + 6 * 8; head = r16(8 + ent * len(nros))
    xo, wo, rows, xs, ws = head, 0, [], [], []
    for n in nros:
        bin_, sz, ((_, a0, b0), (_, a1, b1), (_, a2, b2)) = pieces(n)
        assert len(n) < 16
        rows.append(struct.pack('<16sQQQQQQ', n.encode(), xo, b0 - a0, wo, b1 - a1, xo + (b0 - a0), b2 - a2))
        xs += incbin(bin_, sz, a0, b0) + incbin(bin_, sz, a2, b2); xo += (b0 - a0) + (b2 - a2)
        ws += incbin(bin_, sz, a1, b1); wo += b1 - a1
    idx = struct.pack('<4sI', b'DMNR', len(nros)) + b''.join(rows)
    asm += ['    .section __TEXT,__dmnrox', '    .p2align 14', '    .byte ' + ','.join(str(b) for b in idx), f'    .space {head - len(idx):#x}'] + xs
    asm += ['    .section __DMNRO,__img'] + ws
    flags.append('-Wl,-segprot,__DMNRO,rw,rw')
for n in names:
    hdr = dict(l[2:].split() for l in open(f'{out}/{n}.fixups.tsv'))
    te, po = int(hdr['TEXT_END'], 16), int(hdr['PATCH_OFF'], 16)
    ko, ks = int(hdr['KEY_PAGE_OFF'], 16), int(hdr['KEY_PAGE_SIZE'], 16)
    bin_ = os.path.abspath(f'{out}/{n}.patched.bin'); sz = os.path.getsize(bin_)
    a, end = r16(te), r16(sz)
    if po < 0:   # patch area before the base (patch_nso.py FAR): W ends at the end of data, the loader supplies zero pages for bss and the key page; in the file the patch area follows at FILE_IMAGE_LEN
        fl = int(hdr['FILE_IMAGE_LEN'], 16)
        assert fl % PG == 0 and a <= fl and ko % PG == 0 and ks == PG and ko >= fl
        parts = ((f'__TEXT,__dm{n}x0', 0, a), (f'__DM{n}W,__img', a, fl), (f'__TEXT,__dm{n}x1', fl, end))
    else:
        assert po % PG == 0 and a <= ko and ko + ks <= po and ko % PG == 0 and ks == PG
        parts = ((f'__TEXT,__dm{n}x0', 0, a), (f'__DM{n}W,__img', a, po), (f'__TEXT,__dm{n}x1', po, end))
    for sect, lo, hi in parts:
        assert all(len(x) <= 16 for x in sect.split(','))
        fill = min(hi, sz) - lo
        asm += [f'    .section {sect}', '    .p2align 14', f'    .incbin "{bin_}", {lo:#x}, {fill:#x}']
        if hi - lo > fill: asm.append(f'    .space {hi - lo - fill:#x}')
        asm.append('    .p2align 14')   # Pad the section end to 16K: vm_remap takes whole pages
    flags.append(f'-Wl,-segprot,__DM{n}W,rw,rw')
open(dst, 'w').write('\n'.join(asm) + '\n')
print(' '.join(flags))
